/* Generates, from the PetCARE-dev front end's OWN data and rules:
 *   1. db/migration/V2__reference_data.sql   services, eligibility criteria, id sequences
 *   2. db/seed-demo/V3__demo_seed.sql        demo users (bcrypt), pets, requests, shelter dogs
 *   3. test/resources/eligibility-golden.json  expected results of the JS decision tree
 * so the database and the Java engine stay consistent with the front end.
 *
 * Usage:  cd tools && npm install && node generate-seed.js ../../PetCARE-dev
 */
const fs = require("fs"), path = require("path"), vm = require("vm");
const bcrypt = require("bcryptjs");

const FE = path.resolve(process.argv[2] || "../../PetCARE-dev");
const OUT = path.resolve(__dirname, "..");
const read = f => fs.readFileSync(path.join(FE, "src", f), "utf8");

/* ---- load the front end's classic scripts into one sandbox (same order as index.html) ---- */
const ctx = vm.createContext({ console, Date, Math, JSON, Object, Array, String, Number, parseFloat, isNaN });
vm.runInContext("var DevCredentials = { hash: p => '@@' + p, verify: () => false };", ctx);
for (const f of ["utils/formatting.js","data/constants.js","data/users.js","data/pets.js",
                 "data/services.js","data/mockData.js","services/eligibilityService.js"]) {
  vm.runInContext(read(f), ctx, { filename: f });
}
const run = code => vm.runInContext(code, ctx);
const state = run("seedState()");
const SERVICES = run("SERVICES");

/* ---- SQL helpers ---- */
const q = v => v === null || v === undefined || v === "" ? "NULL"
  : typeof v === "number" ? String(v)
  : typeof v === "boolean" ? (v ? "1" : "0")
  : "'" + String(v).replace(/\\/g, "\\\\").replace(/'/g, "''") + "'";
const insert = (table, cols, rows) => rows.length === 0 ? "" :
  `INSERT INTO ${table} (${cols.join(", ")}) VALUES\n` + rows.map(r => "  (" + r.map(q).join(", ") + ")").join(",\n") + ";\n\n";
const write = (rel, text) => { const p = path.join(OUT, rel); fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, text); console.log("wrote", rel); };

/* ---- V2: reference data ---- */
let v2 = "-- Reference data: service catalogue, eligibility criteria, id sequences.\n-- GENERATED by tools/generate-seed.js from PetCARE-dev (src/data/constants.js, services.js, mockData.js).\n\n";
v2 += insert("veterinary_service", ["name", "sort_order"], SERVICES.map((s, i) => [s, i + 1]));
const crit = [];
for (const svc of Object.keys(state.criteria)) state.criteria[svc].forEach((c, i) => crit.push([svc, c.key, c.label, c.desc, c.enabled, i + 1]));
v2 += insert("eligibility_criterion", ["service_name","criterion_key","label","description","enabled","sort_order"], crit);
const prefixes = { reg: "REG-", req: "REQ-", adopt: "ADOPT-", pet: "P-", user: "U-", notif: "N-", audit: "A-" };
v2 += insert("id_sequence", ["kind","prefix","next_value"], Object.keys(prefixes).map(k => [k, prefixes[k], state.nextIds[k]]));
write("src/main/resources/db/migration/V2__reference_data.sql", v2);

/* ---- V3: demo seed ---- */
let v3 = "-- DEMO DATA ONLY (loaded in the default/dev profile; excluded when the 'prod' profile is active).\n-- GENERATED by tools/generate-seed.js from PetCARE-dev (src/data/users.js, pets.js, mockData.js).\n-- Test passwords are listed in README.md. They are stored here as bcrypt hashes only.\n\n";
const hashPw = h => bcrypt.hashSync(h.replace(/^@@/, ""), 10);
v3 += insert("app_user",
  ["id","role","first_name","middle_name","last_name","full_name","email","mobile","house_street","barangay","city","province","password_hash","status","initials","job_title","must_change_password","verification_code"],
  state.users.map(u => [u.id,u.role,u.firstName,u.middleName,u.lastName,u.name,u.email,u.mobile,u.houseStreet,u.barangay,u.city,u.province,hashPw(u.passwordHash),u.status,u.initials,u.tag,!!u.mustChangePassword,u.verificationCode]));
v3 += insert("pet",
  ["id","owner_id","name","species","breed","sex","dob","color","barangay","registration_status","registered_date","registration_source","weight_kg","health_status","health_notes","rabies_status","last_rabies","deworming_status","last_deworming","proof_of_residency","microchip","microchip_status","kapon_status","kapon_date","photo_url"],
  state.pets.map(p => [p.id,p.ownerId,p.name,p.species,p.breed,p.sex,p.dob,p.color,p.barangay,p.registrationStatus,p.registeredDate,p.registrationSource,p.weight,p.healthStatus,p.healthNotes,p.rabiesStatus,p.lastRabies,p.dewormingStatus,p.lastDeworming,p.proofOfResidency,p.microchip,p.microchipStatus,p.kaponStatus,p.kaponDate,p.photo]));
v3 += insert("pet_registration", ["id","pet_id","owner_id","status","submitted_date","source","rejection_reason"],
  state.registrations.map(r => [r.id,r.petId,r.ownerId,r.status,r.submittedDate,r.source,r.rejectionReason]));
v3 += insert("service_request", ["id","pet_id","owner_id","service_name","remarks","submitted_date","source","staff_decision","decision_date","rejection_reason","status"],
  state.requests.map(r => [r.id,r.petId,r.ownerId,r.service,r.remarks,r.submittedDate,r.source,r.staffDecision,r.decisionDate,r.rejectionReason,r.status]));
/* assessments: ids assigned 1..n in order, so criteria rows can reference them */
const withElig = state.requests.filter(r => r.eligibility);
v3 += insert("eligibility_assessment", ["id","request_id","classification","assessed_date"],
  withElig.map((r, i) => [i + 1, r.id, r.eligibility.classification, r.eligibility.assessedDate]));
const ac = [];
withElig.forEach((r, i) => r.eligibility.criteria.forEach((c, j) => ac.push([i + 1, j + 1, c.label, c.value, c.result, c.basis])));
v3 += insert("eligibility_assessment_criterion", ["assessment_id","seq","label","actual_value","result","basis"], ac);
v3 += insert("service_record", ["request_id","record_date","staff_name","remarks","vaccine_type","batch_number","next_due","microchip_number","procedure_date","post_remarks"],
  state.requests.filter(r => r.serviceRecord).map(r => { const s = r.serviceRecord;
    return [r.id,s.date,s.staff,s.remarks,s.vaccineType,s.batchNumber,s.nextDue,s.microchip,s.procedureDate,s.postRemarks]; }));
v3 += insert("shelter_pet", ["id","name","species","breed","sex","age_text","description","temperament","status","intake_date","photo_url"],
  state.shelterPets.map(s => [s.id,s.name,s.species,s.breed,s.sex,s.age,s.description,s.temperament,s.status,s.intake,s.photo]));
write("src/main/resources/db/seed-demo/V3__demo_seed.sql", v3);

