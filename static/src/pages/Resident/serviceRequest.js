/* ---------------- SERVICE REQUEST WIZARD ---------------- */
function newSvcDraft(){ return {petId:"", service:SERVICES[0], remarks:""}; }
function kaponRequirementsPreview(pet){
  const a = EligibilityService.evaluate(pet, "Kapon / Spay-Neuter");
  return `
  <div class="kapon-preview">
    <div class="kp-title">Kapon / Spay-Neuter Requirements — Preview for ${esc(pet.name)}</div>
    ${a.criteria.map(c=>`<div class="kp-row"><span>${esc(c.label)}</span><span style="font-weight:800;color:${c.result==="PASS"?"var(--green)":c.result==="FAIL"?"var(--danger)":"var(--amber)"};">${c.result}</span></div>`).join("")}
    <p style="font-size:0.68rem;color:var(--muted);margin:10px 0 0;">This is a preview only, based on ${esc(pet.name)}'s current profile. The official Decision Tree-Based Eligibility Classification is generated by CVO staff after submission.</p>
  </div>`;
}
function screenRequestService(walkinOwnerId){
  const isWalkin = !!walkinOwnerId;
  const owner = isWalkin ? userById(walkinOwnerId) : currentUser();
  const verified = verifiedOwnerPets(owner.id);
  if(!UI.wiz.svc) UI.wiz.svc = {step:1, data:newSvcDraft()};
  const w = UI.wiz.svc;
  const d = w.data;

  if(!verified.length && w.step===1){
    return `
    <div class="page-head"><div><div class="crumb">Services</div><h2>Request a Veterinary Service</h2></div></div>
    <div class="card" style="max-width:520px;margin:0 auto;text-align:center;">
      ${emptyState(icoSvg('ban'),"No Verified Pet","You need a verified pet before requesting a veterinary service.",
        isWalkin ? `<button class="btn-red" data-walkin-stage="pet">Register a Pet</button>` : `<button class="btn-red" data-nav="petregistration">Register a Pet</button>`)}
    </div>`;
  }

  const stepHead = `
  <div class="stepper-head">
    ${[1,2,3].map((n,i)=>`<div class="step-dot ${w.step>n?"done":w.step===n?"active":""}">${n}</div>${i<2?`<div class="step-line ${w.step>n?"done":""}"></div>`:""}`).join("")}
  </div>`;

  if(w.step===1){
    if(!d.petId) d.petId = verified[0].id;
    const previewPet = petById(d.petId);
    return `
    <div class="page-head"><div><div class="crumb">Services</div><h2>Request a Veterinary Service</h2></div></div>
    <div class="card" style="max-width:560px;margin:0 auto;">
      ${stepHead}
      ${field("Pet *", `<select id="svc-pet">${verified.map(p=>`<option value="${p.id}" ${d.petId===p.id?"selected":""}>${esc(p.name)} (${p.id})</option>`).join("")}</select>`)}
      ${field("Service *", `<select id="svc-service">${SERVICES.map(s=>`<option ${d.service===s?"selected":""}>${s}</option>`).join("")}</select>`)}
      ${field("Remarks", `<textarea id="svc-remarks" rows="3" placeholder="Anything CVO staff should know...">${esc(d.remarks)}</textarea>`)}
      ${d.service === "Kapon / Spay-Neuter" && previewPet ? kaponRequirementsPreview(previewPet) : ""}
      <div class="wizard-nav">
        <button class="btn-line" id="svc-cancel">Cancel</button>
        <button class="btn-red" id="svc-continue">Continue</button>
      </div>
    </div>`;
  }
  if(w.step===2){
    const pet = petById(d.petId);
    return `
    <div class="page-head"><div><div class="crumb">Services</div><h2>Review Service Request</h2></div></div>
    <div class="card" style="max-width:560px;margin:0 auto;">
      ${stepHead}
      <h3>Pet</h3>
      <div class="kv" style="margin-bottom:14px;">
        <div><div class="k">Pet</div><div class="v">${esc(pet.name)}</div></div>
        <div><div class="k">Species</div><div class="v">${esc(pet.species)}</div></div>
        <div><div class="k">Breed</div><div class="v">${esc(pet.breed)}</div></div>
        <div><div class="k">Age</div><div class="v">${ageString(pet.dob)}</div></div>
        <div><div class="k">Barangay</div><div class="v">${esc(pet.barangay)}</div></div>
      </div>
      <h3>Requested Service</h3>
      <div class="kv" style="margin-bottom:14px;">
        <div><div class="k">Service</div><div class="v">${esc(d.service)}</div></div>
        <div><div class="k">Remarks</div><div class="v">${esc(d.remarks||"—")}</div></div>
      </div>
      <div class="wizard-nav">
        <button class="btn-line" id="svc-back">Back</button>
        <button class="btn-red" id="svc-submit">Submit Request</button>
      </div>
    </div>`;
  }
  // step 3
  const req = reqById(w.createdReqId);
  const pet = req ? petById(req.petId) : null;
  return `
  <div class="page-head"><div><div class="crumb">Services</div><h2>Request Submitted</h2></div></div>
  <div class="card" style="max-width:600px;margin:0 auto;text-align:center;">
    <div style="color:var(--green);">${icoSvg('check',44)}</div>
    <h3 style="border:none;padding:0;">Request Submitted</h3>
    <p style="font-size:0.85rem;color:var(--body);">Request ID: <b>${req?req.id:""}</b><br>Status: Submitted</p>
    <div style="text-align:left;max-width:420px;margin:14px auto 0;">${renderTimeline(requestTimelineSteps(req))}</div>
    <div style="margin-top:18px;">
      ${isWalkin ? `<button class="btn-red" id="walkin-to-eligibility">Continue to Eligibility Assessment</button>`
        : `<button class="btn-red" data-nav="myrequests" data-openreq="${req?req.id:''}">View My Requests</button>`}
    </div>
  </div>`;
}
